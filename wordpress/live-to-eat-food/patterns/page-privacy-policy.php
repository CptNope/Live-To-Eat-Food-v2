<h2 id="h-collect" class="wp-block-heading">What we collect</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p><strong>What you send us.</strong></p>
<!-- /wp:paragraph -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Monthly Crumbs: your email address.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Forms (Woo-pons, events, job posts, suggestions, listing fixes, specials, Your bites photos and Work with Tina): what you type in, such as your name or business, the details of your deal, event or job, and an email address and phone number so we can reply. A photo you share comes with the name or handle you choose.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Paid listings: Stripe takes your card on its own page. We see the amount, whether it was paid and the email address you gave, never your card number.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Listing owners: if you claim your business’s listing, we keep your name, role, phone and email so Tina can confirm it’s yours and we can send you sign-in links. A sign-in link works for two hours and sets no cookie. Each change you make is kept with your email so Tina can see who changed what.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list -->
<!-- wp:paragraph -->
<p><strong>What any visit sends.</strong> Like every website, our host and Cloudflare see your IP address and browser details when you visit, and use them to deliver the site and keep out abuse. To limit how many forms one connection can send in an hour, the site keeps a scrambled (hashed) copy of the IP address for an hour.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p><strong>Visit counts.</strong> We count visits with Independent Analytics, which runs on our own server and doesn’t use cookies. When a page loads, it records the page, the site that sent you there, your browser and type of device, and your approximate location (country and city, worked out from your IP address). It recognizes a returning visitor by a one-way scrambled code made from the IP address and browser, and the key to that code changes every day, so we can’t follow anyone from one day to the next or tell who they are. Your IP address itself isn’t kept. The counts stay on our server, aren’t shared with anyone, and are deleted after two years.</p>
<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>We don’t use ad trackers or tracking pixels.</p>
