<!-- /wp:paragraph -->
<!-- wp:paragraph -->
<p>Videos load only when you press play. Then YouTube (in its privacy-enhanced mode), TikTok, Instagram or Facebook loads its own player, which may set its own cookies under its own privacy policy.</p>
