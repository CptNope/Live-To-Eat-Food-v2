<section class="wp-block-group is-style-sheet ltef-policy has-vinyl-background-color has-background"><!-- wp:group {"anchor":"goal"} -->
<div id="goal" class="wp-block-group"><!-- wp:heading {"anchor":"h-goal"} -->
<h2 id="h-goal" class="wp-block-heading">Our goal</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>We aim to meet the Web Content Accessibility Guidelines (WCAG) 2.2 at level AA on every page of livetoeatfoodie.com.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"anchor":"done"} -->
<div id="done" class="wp-block-group"><!-- wp:heading {"anchor":"h-done"} -->
<h2 id="h-done" class="wp-block-heading">What the site does</h2>
<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Text and buttons meet AA color contrast, and meaning never rests on color alone: every label (Tina ate here, Paid ad, Woo-pon) has a word and an icon.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Everything works with a keyboard, with a visible focus ring and a “Skip to content” link at the top of every page.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Pages fit a screen 320 pixels wide without scrolling sideways, so you can zoom in as far as you need.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Every form field has a label, optional fields say so, and errors say in words what to fix.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>When your device is set to reduce motion, the site turns its animations off.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Videos load only when you press play, and each one has a link to watch it on the platform it came from.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></div>
<!-- /wp:group -->
<!-- wp:group {"anchor":"checked"} -->
<div id="checked" class="wp-block-group"><!-- wp:heading {"anchor":"h-checked"} -->
<h2 id="h-checked" class="wp-block-heading">How we checked</h2>
<!-- /wp:heading -->
<!-- wp:paragraph -->
<p>On November 11, 2026, we tested 27 kinds of page at desktop and phone sizes with the axe-core checker, using its WCAG 2.2 A and AA rules, and fixed what it found. We also checked keyboard focus, fitting a 320-pixel screen and reduced motion on each of them. Automated checks don’t catch everything, which is why your reports matter.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->
<!-- wp:group {"anchor":"limits"} -->
<div id="limits" class="wp-block-group"><!-- wp:heading {"anchor":"h-limits"} -->
<h2 id="h-limits" class="wp-block-heading">What isn’t perfect yet</h2>
<!-- /wp:heading -->
<!-- wp:list -->
<ul class="wp-block-list"><!-- wp:list-item -->
<li>Tina’s videos play in YouTube, TikTok, Instagram or Facebook’s own players. Their controls and captions come from those platforms, so we can’t change them; we ask the YouTube and TikTok players to show captions whenever a video has them.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>VIP Woo-pon flyers are made by the businesses and may be images without text. The deal, the dates and the fine print are always written out on the Woo-pon itself.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>Forms use Cloudflare Turnstile to stop spam. Most people never see it; if it ever blocks you, email us what you wanted to send.</li>
<!-- /wp:list-item -->
<!-- wp:list-item -->
<li>The map on Explore is a visual shortcut. Every neighborhood on it is also in the filter above the list.</li>
<!-- /wp:list-item --></ul>
<!-- /wp:list --></div>
